from __future__ import annotations

import random
from typing import Optional, Dict, Any


class FeedbackRules:
    """
    Правила генерации ответов на отзывы.

    Сейчас логика простая:
    - оценка 1–3  → вежливое "спасибо, учтём замечания"
    - оценка 4–5  → тёплое "спасибо за высокую оценку"
    Имя клиента подставляем, если оно есть в объекте отзыва.
    """

    # ----- ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ -----

    @staticmethod
    def _extract_name(feedback: Dict[str, Any]) -> Optional[str]:
        """
        Пытаемся достать имя покупателя из разных полей.
        Если имени нет — возвращаем None.
        """
        # На разных версиях API имя может лежать по-разному
        name = None

        # Популярные поля
        name = feedback.get("userName") or feedback.get("wbUserName") or name

        details = feedback.get("wbUserDetails") or feedback.get("userDetails")
        if isinstance(details, dict):
            name = details.get("name") or details.get("userName") or name

        if not name:
            return None

        name = str(name).strip()
        if not name:
            return None

        # Берём только первое слово, если там "Иван Иванов"
        return name.split()[0]

    @staticmethod
    def _rating_type(rating: int) -> str:
        """
        Классифицируем оценку.
        """
        if rating <= 0:
            return "unknown"
        if rating <= 3:
            return "low"
        return "high"  # 4–5

    # ----- ОСНОВНОЙ МЕТОД -----

    @classmethod
    def make_reply(cls, feedback: Dict[str, Any]) -> str:
        """
        Сгенерировать текст ответа на отзыв по рейтингу и имени.
        """
        rating = int(feedback.get("productValuation") or 0)
        rtype = cls._rating_type(rating)
        name = cls._extract_name(feedback)

        # Шаблоны для низких оценок (1–3)
        negative_templates_with_name = [
            "{name}, большое спасибо за ваш отзыв. Мы обязательно учтём указанные замечания и сделаем всё, чтобы в следующий раз всё было на высшем уровне.",
            "{name}, благодарим вас за обратную связь. Нам очень важно понимать, что можно улучшить, и мы уже взяли ваши замечания в работу. Постараемся, чтобы в следующий раз вы остались довольны на все 5⭐.",
            "{name}, спасибо, что поделились мнением. Нам искренне жаль, что впечатление оказалось не идеальным. Мы обязательно учтём ваши слова и улучшим качество сервиса и товара.",
        ]

        negative_templates_no_name = [
            "Большое спасибо за ваш отзыв. Мы обязательно учтём указанные замечания и сделаем всё, чтобы в следующий раз всё было на высшем уровне.",
            "Благодарим за обратную связь. Нам очень важно понимать, что можно улучшить, и мы уже взяли ваши замечания в работу. Постараемся, чтобы в следующий раз вы остались довольны на все 5⭐.",
            "Спасибо, что поделились мнением. Нам искренне жаль, что впечатление оказалось не идеальным. Мы учтём ваши слова и постараемся стать лучше.",
        ]

        # Шаблоны для высоких оценок (4–5)
        positive_templates_with_name = [
            "{name}, позвольте поблагодарить вас за обратную связь и такую высокую оценку нашего товара. Для нас очень важно, чтобы клиент всегда оставался довольным. Ещё раз примите слова признательности за то, что так высоко оценили качество товара и нашу работу 💜",
            "{name}, огромное спасибо за ваш отзыв и высокую оценку! Нам очень приятно, что товар вам понравился. Мы и дальше будем стараться радовать вас качеством и сервисом.",
            "{name}, благодарим вас за столь тёплые слова и высокую оценку. Ваша поддержка помогает нам становиться ещё лучше. Спасибо, что выбрали нас!",
        ]

        positive_templates_no_name = [
            "Позвольте поблагодарить вас за обратную связь и такую высокую оценку нашего товара. Для нас очень важно, чтобы клиент всегда оставался довольным. Ещё раз примите слова признательности за то, что так высоко оценили качество товара и нашу работу 💜",
            "Огромное спасибо за ваш отзыв и высокую оценку! Нам очень приятно, что товар вам понравился. Мы и дальше будем стараться радовать вас качеством и сервисом.",
            "Благодарим вас за столь тёплые слова и высокую оценку. Ваша поддержка помогает нам становиться ещё лучше. Спасибо, что выбрали нас!",
        ]

        # ----- Выбор текста по типу оценки -----

        if rtype == "low":
            if name:
                template = random.choice(negative_templates_with_name)
                return template.format(name=name)
            else:
                return random.choice(negative_templates_no_name)

        if rtype == "high":
            if name:
                template = random.choice(positive_templates_with_name)
                return template.format(name=name)
            else:
                return random.choice(positive_templates_no_name)

        # На всякий случай дефолт
        if name:
            return f"{name}, спасибо за ваш отзыв! Нам очень важна ваша обратная связь."
        return "Спасибо за ваш отзыв! Нам очень важна ваша обратная связь."


